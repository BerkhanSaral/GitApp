package d3_datatypes_concat_operators;

public class Concatenation {
    public static void main(String[] args) {
        String variable = "Hello";
        int a = 12, b = 22;
        System.out.println((a + b) + variable);
        System.out.println(variable + a * b);
        System.out.println(a+b+variable);



    }
}
